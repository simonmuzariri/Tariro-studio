  await page.keyboard.press('Control+s');
  await expect(page.getByTestId('dirty')).toHaveCount(0);
  await expect(page).toHaveTitle('Robot — Tariro Studio');
  expect(existsSync(file)).toBe(true);

  // Second save goes to the same path without a dialog.
  await stubDialog('save', join(dir, 'WRONG.tsp'));
  await rename('Robot v2');
  await page.getByTestId('file-menu').click();
  await page.getByTestId('menu-save').click();
  await expect(page.getByTestId('dirty')).toHaveCount(0);
  expect(existsSync(join(dir, 'WRONG.tsp'))).toBe(false);

  // Start something new, then open the saved file again.
  await page.getByTestId('file-menu').click();
  await page.getByTestId('menu-new').click();
  await expect(page.getByTestId('project-name')).toHaveValue('My Project');
