test('M5: switching to code makes the C++ editable, hides the blocks and still compiles', async () => {
  await page.getByTestId('edit-as-code').click();
  await expect(page.getByRole('dialog', { name: 'Switch to code?' })).toBeVisible();
  await page.getByTestId('choice-cancel').click();
  await expect(page.getByTestId('block-workspace')).toBeVisible();

  await page.getByTestId('edit-as-code').click();
  await page.getByTestId('choice-confirm').click();
  await expect(page.getByTestId('block-workspace')).toHaveCount(0);
  await expect(page.getByTestId('dirty')).toBeVisible();
  await expect(code()).toContainText('Converted from blocks. This code is now edited by hand.');
  await expect(code()).not.toContainText('Edit the blocks');

  // Type at the very top of the file; the text must reach the project (and so the compiler).
  await page.getByTestId('code-view').locator('.view-lines').click();
  await page.keyboard.press('Control+Home');
  await page.keyboard.type('// my own code\n');
  await expect(code()).toContainText('// my own code');
  await page.getByTestId('verify').click();
  await expect(page.getByTestId('build-status')).toContainText('Compiled successfully');
  const sketch = readFileSync(join(profile, 'build', readdirSync(join(profile, 'build'))[0]!, 'sketch', 'sketch.ino'), 'utf8');
  expect(sketch.startsWith('// my own code\n')).toBe(true);
});

