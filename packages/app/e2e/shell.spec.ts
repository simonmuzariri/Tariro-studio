// ───────────────────────── M3: projects ─────────────────────────

/** Make the next native save/open dialog return `path` (dialogs cannot be clicked in tests). */
async function stubDialog(kind: 'save' | 'open', path: string) {
  await app!.evaluate(
    ({ dialog }, { kind, path }) => {
      if (kind === 'save') dialog.showSaveDialog = (async () => ({ canceled: false, filePath: path })) as typeof dialog.showSaveDialog;
      else dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [path] })) as typeof dialog.showOpenDialog;
    },
    { kind, path },
  );
}

async function rename(name: string) {
  const input = page.getByTestId('project-name');
  await input.fill(name);
  await expect(page.getByTestId('dirty')).toBeVisible();
}

test('M3: save, keep editing, save again to the same file, then reopen it', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'tariro-docs-'));
  const file = join(dir, 'Robot.tsp');
  await rename('Robot');
  await stubDialog('save', file);
  await page.keyboard.press('Control+s');
  await expect(page.getByTestId('dirty')).toHaveCount(0);
  await expect(page).toHaveTitle('Robot — Tariro Studio');
  expect(existsSync(file)).toBe(true);

  // Second save goes to the same path without a dialog.
  await stubDialog('save', join(dir, 'WRONG.tsp'));
  await rename('Robot v2');
  await page.getByTestId('file-menu').click();
  await page.getByTestId('menu-save').click();
  await expect(page.getByTestId('dirty')).toHaveCount(0);
  expect(existsSync(join(dir, 'WRONG.tsp'))).toBe(false);

  // Start something new, then open the saved file again.
  await page.getByTestId('file-menu').click();
  await page.getByTestId('menu-new').click();
  await expect(page.getByTestId('project-name')).toHaveValue('My Project');
  await stubDialog('open', file);
  await page.getByTestId('file-menu').click();
  await page.getByTestId('menu-open').click();
  await expect(page.getByTestId('project-name')).toHaveValue('Robot v2');
  await expect(page.getByTestId('dirty')).toHaveCount(0);
  rmSync(dir, { recursive: true, force: true });
});

