test('M1: dragging a pin block into forever updates the code', async () => {
  // The category row (toolboxitemid "pins") receives the click, not its inner label.
  await page.locator('.blocklyToolboxCategory#pins').click();
  const source = page.locator('.blocklyFlyout .blocklyDraggable').filter({ hasText: 'set pin' }).first();
  await expect(source).toBeVisible();
  // Innermost block in the main workspace whose text contains "forever" is the forever block itself.
  const forever = page.locator('svg.blocklySvg .blocklyBlockCanvas .blocklyDraggable').filter({ hasText: 'forever' }).last();
  const from = (await source.boundingBox())!;
  const to = (await forever.boundingBox())!;
  // Grab the block near its top-left and drop it so its top-left lands in the forever "mouth".
  await page.mouse.move(from.x + 12, from.y + 14);
  await page.mouse.down();
  await page.mouse.move(to.x + 60, to.y + 80, { steps: 15 });
  await page.mouse.move(to.x + 30, to.y + 54, { steps: 5 });
  await page.mouse.up();
  await expect(code()).toContainText('digitalWrite(13, HIGH);');
  await expect(code()).toContainText('pinMode(13, OUTPUT);');
});

