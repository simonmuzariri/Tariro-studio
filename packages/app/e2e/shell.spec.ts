let profile: string;

const fakeCli = fakeCliPath();

async function launch(env: Record<string, string> = {}, reuseProfile = false) {
  // Fresh profile per launch so autosaves never leak between tests (unless a test reuses it to
  // simulate a restart). Hardware is mocked: a virtual Tariro on /dev/ttyMOCK0 and a fake
  // arduino-cli (unless a test overrides it).
  if (!reuseProfile) profile = mkdtempSync(join(tmpdir(), 'tariro-e2e-'));
  app = await electron.launch({
    args: [appDir, `--user-data-dir=${profile}`],
    env: { ...process.env, TARIRO_SERIAL_MOCK: '1', TARIRO_ARDUINO_CLI: fakeCli, ...env } as Record<string, string>,
  });
  page = await app.firstWindow();
  await expect(page).toHaveTitle(/Tariro Studio$/);
}

// eslint-disable-next-line no-empty-pattern -- Playwright passes fixtures first; none are needed here.
test.beforeEach(async ({}, info) => {
  // "M…b" and "PY:" tests launch the app themselves (with a different mock board).
  if (!/^(M\d+b|PY:|STAGE:|AI:|SAFETY:|TELLO:)/.test(info.title)) await launch();
});

test.afterEach(async () => {
  if (app) {
    // Never let a "save changes?" guard keep a test window open.
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach((w) => w.destroy())).catch(() => {});
    await app.close().catch(() => {});
  }
  app = undefined;
  if (profile) rmSync(profile, { recursive: true, force: true });
});

