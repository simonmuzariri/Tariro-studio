test('M3b: work survives a crash and is offered back on the next start', async () => {
  await launch();
  await rename('Crash test');
  // Autosave runs on blur (and every 30 s); trigger it, then kill the app without a clean exit.
  await page.evaluate(() => (globalThis as unknown as EventTarget).dispatchEvent(new Event('blur')));
  await expect.poll(() => readdirSync(join(profile, 'autosave')).length).toBeGreaterThan(0);
  app!.process().kill('SIGKILL');
  app = undefined;

  await launch({}, true);
  const dialog = page.getByRole('dialog', { name: 'Recover your work?' });
  await expect(dialog).toContainText('Crash test');
  await page.getByTestId('recover').click();
  await expect(page.getByTestId('project-name')).toHaveValue('Crash test');
  await expect(page.getByTestId('dirty')).toBeVisible();
});

